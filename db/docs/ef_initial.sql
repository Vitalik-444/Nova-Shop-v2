CREATE TABLE categories (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    name text NOT NULL,
    parent_id integer,
    CONSTRAINT pk_categories PRIMARY KEY (id),
    CONSTRAINT fk_categories_categories_parent_id FOREIGN KEY (parent_id) REFERENCES categories (id) ON DELETE RESTRICT
);

CREATE TABLE users (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    full_name text NOT NULL,
    email character varying(254) NOT NULL,
    password_hash text NOT NULL,
    role character varying(20) NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT (now()),
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT chk_users_role_allowed CHECK (role IN ('buyer', 'seller', 'moderator', 'admin'))
);

CREATE TABLE orders (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    buyer_id integer,
    status character varying(20) NOT NULL DEFAULT 'pending',
    created_at timestamp with time zone NOT NULL DEFAULT (now()),
    CONSTRAINT pk_orders PRIMARY KEY (id),
    CONSTRAINT chk_orders_status_allowed CHECK (status IN ('pending', 'paid', 'shipped', 'delivered', 'cancelled')),
    CONSTRAINT fk_orders_users_buyer_id FOREIGN KEY (buyer_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE TABLE products (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    seller_id integer NOT NULL,
    category_id integer NOT NULL,
    title text NOT NULL,
    description text,
    price numeric(10,2) NOT NULL,
    stock integer NOT NULL DEFAULT 0,
    created_at timestamp with time zone NOT NULL DEFAULT (now()),
    CONSTRAINT pk_products PRIMARY KEY (id),
    CONSTRAINT chk_products_price_positive CHECK (price > 0),
    CONSTRAINT chk_products_stock_nonnegative CHECK (stock >= 0),
    CONSTRAINT fk_products_categories_category_id FOREIGN KEY (category_id) REFERENCES categories (id) ON DELETE RESTRICT,
    CONSTRAINT fk_products_users_seller_id FOREIGN KEY (seller_id) REFERENCES users (id) ON DELETE RESTRICT
);

CREATE TABLE order_items (
    order_id integer NOT NULL,
    product_id integer NOT NULL,
    quantity integer NOT NULL,
    price_at_purchase numeric(10,2) NOT NULL,
    CONSTRAINT pk_order_items PRIMARY KEY (order_id, product_id),
    CONSTRAINT chk_order_items_price_positive CHECK (price_at_purchase > 0),
    CONSTRAINT chk_order_items_quantity_positive CHECK (quantity > 0),
    CONSTRAINT fk_order_items_orders_order_id FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT fk_order_items_products_product_id FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT
);

CREATE TABLE product_reviews (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    product_id integer NOT NULL,
    buyer_id integer,
    rating smallint NOT NULL,
    comment text,
    created_at timestamp with time zone NOT NULL DEFAULT (now()),
    CONSTRAINT pk_product_reviews PRIMARY KEY (id),
    CONSTRAINT product_reviews_rating_check CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT fk_product_reviews_products_product_id FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE,
    CONSTRAINT fk_product_reviews_users_buyer_id FOREIGN KEY (buyer_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE TABLE user_cart (
    user_id integer NOT NULL,
    product_id integer NOT NULL,
    quantity integer NOT NULL DEFAULT 1,
    added_at timestamp with time zone NOT NULL DEFAULT (now()),
    CONSTRAINT pk_user_cart PRIMARY KEY (user_id, product_id),
    CONSTRAINT chk_user_cart_quantity_positive CHECK (quantity > 0),
    CONSTRAINT fk_user_cart_products_product_id FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE,
    CONSTRAINT fk_user_cart_users_user_id FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE user_favorites (
    user_id integer NOT NULL,
    product_id integer NOT NULL,
    added_at timestamp with time zone NOT NULL DEFAULT (now()),
    CONSTRAINT pk_user_favorites PRIMARY KEY (user_id, product_id),
    CONSTRAINT fk_user_favorites_products_product_id FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE,
    CONSTRAINT fk_user_favorites_users_user_id FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

