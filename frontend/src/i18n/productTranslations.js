export function getProductTitle(productOrTitle, lang = "uk") {
    if (!productOrTitle) return "";
    if (typeof productOrTitle === "object") {
        if (lang === "uk") {
            return productOrTitle.titleUk || PRODUCT_TRANSLATIONS_UK[productOrTitle.title] || productOrTitle.title;
        }
        return productOrTitle.titleEn || productOrTitle.title;
    }
    if (lang === "en") return productOrTitle;
    return PRODUCT_TRANSLATIONS_UK[productOrTitle] || productOrTitle;
}

export function getCategoryTitle(categoryOrSlug, lang = "uk") {
    if (!categoryOrSlug) return "";
    const slug = typeof categoryOrSlug === "object" ? categoryOrSlug.slug : categoryOrSlug;
    if (lang === "en") {
        if (CATEGORY_TRANSLATIONS_EN[slug]) return CATEGORY_TRANSLATIONS_EN[slug];
        if (typeof categoryOrSlug === "object" && (categoryOrSlug.nameEn || categoryOrSlug.name)) {
            return categoryOrSlug.nameEn || categoryOrSlug.name;
        }
        return slug.split("-").map(w => w.charAt(0).toUpperCase() + w.slice(1)).join(" ");
    }
    if (CATEGORY_TRANSLATIONS_UK[slug]) return CATEGORY_TRANSLATIONS_UK[slug];
    if (typeof categoryOrSlug === "object" && (categoryOrSlug.nameUk || categoryOrSlug.name)) {
        return categoryOrSlug.nameUk || categoryOrSlug.name;
    }
    return CATEGORY_TRANSLATIONS_EN[slug] || slug;
}
